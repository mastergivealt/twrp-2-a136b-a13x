#!/usr/bin/env python3
"""Read the STOCK recovery.img and write what the device tree needs from it:
prebuilt/kernel, prebuilt/dtb, boot header parameters, ramdisk compression, cmdline.
Optional probe dir (getprop.txt, super_size.txt) refines codename / platform / super size.
Usage: gen_from_stock.py <stock recovery.img> <device tree dir> [probe dir]"""
import os, re, struct, sys

def align(x, p): return (x + p - 1) // p * p

def main():
    img, out = sys.argv[1], sys.argv[2]
    probe = sys.argv[3] if len(sys.argv) > 3 else None
    d = open(img, 'rb').read()
    if d[:8] != b'ANDROID!':
        sys.exit("ERROR: %s is not an Android boot image (no ANDROID! magic)" % img)
    ver = struct.unpack_from('<I', d, 40)[0]
    if ver <= 2:
        (ksz, kaddr, rsz, raddr, ssz, saddr, taddr, page, _v) = struct.unpack_from('<9I', d, 8)
        cmd = d[64:64 + 512].split(b'\0')[0] + d[608:608 + 1024].split(b'\0')[0]
        dtb_sz, dtb_addr, rdtbo = 0, 0, 0
        if ver >= 1:
            rdtbo = struct.unpack_from('<I', d, 1632)[0]
        if ver == 2:
            dtb_sz = struct.unpack_from('<I', d, 1648)[0]
            dtb_addr = struct.unpack_from('<Q', d, 1652)[0]
        off = page
        kernel = d[off:off + ksz]; off += align(ksz, page)
        ramdisk = d[off:off + rsz]; off += align(rsz, page)
        off += align(ssz, page)
        off += align(rdtbo, page)
        dtb = d[off:off + dtb_sz]
        base = kaddr - 0x8000 if (kaddr & 0xFFFF) == 0x8000 else 0
        offs = dict(kernel=kaddr - base, ramdisk=raddr - base, second=saddr - base,
                    tags=taddr - base, dtb=(dtb_addr - base) if dtb_sz else 0)
    else:  # v3 / v4
        ksz, rsz = struct.unpack_from('<2I', d, 8)
        page, base = 4096, 0
        cmd = d[44:44 + 1536].split(b'\0')[0]
        kernel = d[page:page + ksz]
        ramdisk = d[page + align(ksz, page):][:rsz]
        dtb = b''
        offs = dict(kernel=0x8000, ramdisk=0x1000000, second=0, tags=0, dtb=0)
        print("WARNING: header v%d image: this tree is written for v0-v2, expect to adjust" % ver)

    cmdline = cmd.decode('ascii', 'replace').strip()
    pre = os.path.join(out, 'prebuilt'); os.makedirs(pre, exist_ok=True)
    open(os.path.join(pre, 'kernel'), 'wb').write(kernel)
    if dtb: open(os.path.join(pre, 'dtb'), 'wb').write(dtb)

    if ramdisk[:2] == b'\x1f\x8b': comp = 'gzip'
    elif ramdisk[:4] in (b'\x02\x21\x4c\x18', b'\x04\x22\x4d\x18'): comp = 'lz4'
    else: comp = 'unknown'

    codename, platform, board, super_size = 'a13x', 'mt6833', 'mt6833', 0
    if probe and os.path.isdir(probe):
        gp = os.path.join(probe, 'getprop.txt')
        if os.path.exists(gp):
            props = dict(re.findall(r'\[([^\]]+)\]: \[([^\]]*)\]', open(gp, errors='ignore').read()))
            codename = props.get('ro.product.device') or codename
            platform = props.get('ro.board.platform') or platform
            board = props.get('ro.product.board') or platform
        sp = os.path.join(probe, 'super_size.txt')
        if os.path.exists(sp):
            m = re.search(r'\d{6,}', open(sp, errors='ignore').read())
            if m: super_size = int(m.group())

    h = lambda v: '0x%08x' % v
    L = ['# GENERATED by tools/gen_from_stock.py from the stock recovery.img - do not edit',
         'GEN_PRODUCT_DEVICE := %s' % codename,
         'GEN_PLATFORM := %s' % platform,
         'GEN_BOARD := %s' % board,
         'GEN_HEADER_VERSION := %d' % ver,
         'GEN_PAGESIZE := %d' % page,
         'GEN_BASE := %s' % h(base),
         'GEN_KERNEL_OFFSET := %s' % h(offs['kernel']),
         'GEN_RAMDISK_OFFSET := %s' % h(offs['ramdisk']),
         'GEN_SECOND_OFFSET := %s' % h(offs['second']),
         'GEN_TAGS_OFFSET := %s' % h(offs['tags']),
         'GEN_DTB_OFFSET := %s' % h(offs['dtb']),
         'GEN_HAS_DTB := %s' % ('true' if dtb else 'false'),
         'GEN_RAMDISK_LZ4 := %s' % ('true' if comp == 'lz4' else 'false'),
         'GEN_CMDLINE := %s' % cmdline.replace('#', '\\#').replace('$', '$$')]
    if super_size: L.append('GEN_SUPER_SIZE := %d' % super_size)
    open(os.path.join(out, 'generated.mk'), 'w').write('\n'.join(L) + '\n')

    print('stock image: header v%d, page %d, base %s, ramdisk %s, kernel %d B, dtb %d B' %
          (ver, page, h(base), comp, len(kernel), len(dtb)))
    print('cmdline:', cmdline)
    print('codename=%s platform=%s super=%s' % (codename, platform, super_size or 'default'))

main()
